// Helper to calculate ISO date relative to today
export const getRelativeDate = (offsetDays: number, hourOffset = 0): string => {
  const d = new Date();
  d.setDate(d.getDate() + offsetDays);
  d.setHours(d.getHours() + hourOffset);
  return d.toISOString();
};

